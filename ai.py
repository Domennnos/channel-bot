"""
Работа с Claude (Anthropic API) + защита от лишних трат.

Перед КАЖДЫМ запросом проверяем дневные лимиты (число запросов и сумма в долларах).
Если лимит исчерпан — запрос не отправляется и ничего не тратится.
"""
import anthropic

import config
import db

# Цены в долларах за 1 миллион «токенов» (токен — это примерно 3–4 буквы текста): (вход, выход).
ЦЕНЫ = {
    "claude-opus-5-5": (4.0, 20.0),
    "claude-sonnet-5-5": (2.0, 10.0),
    "claude-haiku-5-5": (0.10, 0.50),
    "claude-fable-5-1": (10.0, 50.0),
}
ЦЕНА_НА_ВСЯКИЙ_СЛУЧАЙ = (10.0, 50.0)  # если модель незнакомая — считаем по самой дорогой


class ЛимитИсчерпан(Exception):
    """Дневной лимит запросов или денег закончился."""


class ОшибкаИИ(Exception):
    """Claude не смог ответить (отказ, обрыв, сеть и т.п.)."""


_клиент = None


def _получить_клиента() -> anthropic.Anthropic:
    global _клиент
    if _клиент is None:
        # Ключ берём явно из .env; в логи он не попадает.
        _клиент = anthropic.Anthropic(
            api_key=config.ANTHROPIC_API_KEY,
            base_url=config.ANTHROPIC_BASE_URL or None,  # None = обычный адрес Anthropic
            # Посредники (getapi и т.п.) принимают только классическую версию протокола.
            default_headers={"anthropic-version": "2023-06-01"} if config.ANTHROPIC_BASE_URL else None,
            max_retries=1, timeout=300.0,  # посредник бывает медленным — ждём до 5 минут
        )
    return _клиент


def _проверить_лимиты(настройки: dict) -> None:
    лимиты = настройки["лимиты"]
    запросов, потрачено = db.расход_за_сегодня()
    if запросов >= лимиты["запросов_в_сутки"]:
        raise ЛимитИсчерпан(
            f"Дневной лимит запросов к ИИ исчерпан ({запросов} из {лимиты['запросов_в_сутки']}). "
            "Завтра бот снова заработает. Лимит можно поменять в settings.json."
        )
    if потрачено >= лимиты["долларов_в_сутки"]:
        raise ЛимитИсчерпан(
            f"Дневной лимит расходов исчерпан (${потрачено:.2f} из ${лимиты['долларов_в_сутки']:.2f}). "
            "Завтра бот снова заработает. Лимит можно поменять в settings.json."
        )


def _стоимость(модель: str, usage) -> float:
    цена_вх, цена_вых = ЦЕНЫ.get(модель, ЦЕНА_НА_ВСЯКИЙ_СЛУЧАЙ)
    return (usage.input_tokens * цена_вх + usage.output_tokens * цена_вых) / 1_000_000


def спросить(система: str, запрос: str, *, макс_токенов: int = 3000) -> str:
    """Один запрос к Claude. Возвращает текст ответа. Считает расход."""
    настройки = config.загрузить_настройки()
    _проверить_лимиты(настройки)
    модель = настройки["ии"]["модель"]

    параметры = dict(
        model=модель,
        max_tokens=макс_токенов,  # жёсткий потолок длины ответа — тоже защита от трат
        system=система,
        messages=[{"role": "user", "content": запрос}],
        # «усилие» — насколько долго модель думает; low = дешевле и быстрее, для постов хватает
        output_config={"effort": настройки["ии"].get("усилие_размышления", "low")},
    )
    try:
        try:
            ответ = _получить_клиента().messages.create(**параметры)
        except anthropic.BadRequestError as e:
            # Некоторые посредники не знают параметр «усилие» — пробуем ещё раз без него.
            if "output_config" not in str(e) and "effort" not in str(e).lower():
                raise
            параметры.pop("output_config")
            ответ = _получить_клиента().messages.create(**параметры)
    except anthropic.AuthenticationError as e:
        raise ОшибкаИИ("Ключ ИИ не принят (AuthenticationError). Проверьте ключ и адрес сервера (ANTHROPIC_BASE_URL).") from e
    except anthropic.APIStatusError as e:
        # Показываем код и короткое пояснение сервера — ключа в них нет.
        raise ОшибкаИИ(f"ИИ вернул ошибку {e.status_code}: {str(e.message)[:200]}") from e
    except anthropic.APIError as e:
        raise ОшибкаИИ(f"Не удалось связаться с ИИ: {type(e).__name__}") from e

    # Записываем расход сразу после ответа (даже если ответ окажется пустым).
    db.записать_расход(_стоимость(модель, ответ.usage))

    if ответ.stop_reason == "refusal":
        raise ОшибкаИИ("Claude отказался отвечать на этот запрос. Попробуйте переформулировать тему.")
    текст = "".join(b.text for b in ответ.content if b.type == "text").strip()
    if not текст:
        raise ОшибкаИИ("Claude вернул пустой ответ. Попробуйте ещё раз.")
    return текст


# ---------- Описание стиля канала (из settings.json) ----------

def _описание_стиля(настройки: dict) -> str:
    к = настройки["канал"]
    return (
        f"О чём канал: {к['о_чём']}\n"
        f"Для кого: {к['для_кого']}\n"
        f"Тон: {к['тон']}\n"
        f"Длина постов: {к['длина']}\n"
        f"Эмодзи: {к['эмодзи']}\n"
        f"Язык: {к['язык']}"
    )


ПРАВИЛА_ПОСТОВ = """Правила:
- Пиши от первого лица, как сам автор, живым человеческим языком, без канцелярита и без «шаблонной» бодрости.
- НЕ выдумывай конкретные факты из жизни автора (цифры, даты, имена, события, достижения, покупки), которых нет в заметке автора. Если фактов нет — пиши в виде размышления, наблюдения, вопроса к читателям или универсального опыта, не приписывая автору конкретных выдуманных случаев.
- Никакой разметки (без звёздочек, решёток, markdown) и без хэштегов — только обычный текст и абзацы.
- В конце можно добавить короткий вопрос читателям, но не в каждом посте.
- Выдай ТОЛЬКО текст поста — без вступлений вроде «Вот пост:», без пояснений и без кавычек вокруг."""


def написать_пост(*, заметка: str | None, прошлые_посты: list[str], лучшие_посты: list[str],
                  правки: str | None = None, черновик: str | None = None) -> str:
    """Пишет новый пост или переписывает черновик по вашим правкам."""
    настройки = config.загрузить_настройки()
    система = (
        "Ты — автор личного Telegram-канала и пишешь посты в его стиле.\n\n"
        f"{_описание_стиля(настройки)}\n\n{ПРАВИЛА_ПОСТОВ}"
    )

    части = []
    if прошлые_посты:
        части.append(
            "Недавние посты канала (для стиля и чтобы не повторяться):\n"
            + "\n---\n".join(п[:600] for п in прошлые_посты)
        )
    if лучшие_посты:
        части.append(
            "Посты, которые читателям понравились больше всего (бери из них удачные приёмы):\n"
            + "\n---\n".join(п[:600] for п in лучшие_посты)
        )

    if черновик and правки:
        части.append(f"Текущий черновик:\n{черновик}\n\nПерепиши его с учётом правок автора: {правки}")
    elif черновик:
        части.append(
            f"Текущий черновик:\n{черновик}\n\nНапиши другой вариант этого поста: "
            "другая подача и другие слова, та же основа."
        )
    elif заметка:
        части.append(f"Заметка автора — напиши по ней пост:\n{заметка}")
    else:
        части.append(
            "Придумай тему для нового поста из тем канала (чередуй темы, не повторяй недавние) "
            "и напиши пост."
        )
    return спросить(система, "\n\n".join(части), макс_токенов=3000)


def подготовить_отчёт(данные_по_постам: str) -> str:
    """Недельный отчёт: что зашло, что нет, идеи на следующую неделю."""
    настройки = config.загрузить_настройки()
    система = (
        "Ты — помощник автора личного Telegram-канала. Ты делаешь для него простой понятный "
        "еженедельный отчёт на русском языке, обычным текстом без разметки.\n\n"
        f"{_описание_стиля(настройки)}"
    )
    запрос = (
        "Вот посты за неделю с реакциями и комментариями:\n\n"
        f"{данные_по_постам}\n\n"
        "Сделай отчёт:\n"
        "1) Что зашло лучше всего (1–2 поста) и почему, по твоему мнению.\n"
        "2) Что зашло хуже и что можно улучшить.\n"
        "3) О чём говорят в комментариях (если они есть).\n"
        "4) 3–5 идей для следующих постов — каждая в одну строку, с учётом того, что зашло.\n"
        "Пиши коротко и дружелюбно. Если данных мало (мало реакций) — честно скажи, что выводы "
        "предварительные."
    )
    return спросить(система, запрос, макс_токенов=2500)


def предложить_ответ(*, текст_поста: str, комментарий: str) -> str:
    """Предлагает ответ на комментарий читателя от имени автора."""
    настройки = config.загрузить_настройки()
    система = (
        "Ты отвечаешь на комментарии читателей от имени автора личного Telegram-канала.\n\n"
        f"{_описание_стиля(настройки)}\n\n"
        "Правила: ответ короткий (1–3 предложения), тёплый, в стиле автора. Не выдумывай факты "
        "об авторе и не давай обещаний от его имени. Без разметки. Если комментарий — спам, "
        "оскорбление или вопрос, на который ты не можешь честно ответить без автора, выдай ровно "
        "слово ПРОПУСТИТЬ. Выдай только текст ответа."
    )
    запрос = f"Пост:\n{текст_поста[:1500]}\n\nКомментарий читателя:\n{комментарий[:800]}"
    return спросить(система, запрос, макс_токенов=600)
